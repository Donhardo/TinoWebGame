  // allunga le righe e copia il pavimento; restituisce un errore se la stanza non va
  function prepara(def) {
    const r = def.righe.slice();
    while (r.length < 22) r.push('');
    if (r.length > 22) return 'più di 22 righe';
    const larga = Math.max(...r.map(s => s.length));
    for (let i = 18; i < 22; i++) if (!r[i]) r[i] = r[17].replace(/[^#%]/g, '.');
    for (let i = 0; i < 22; i++) {
      if (i >= 17 && r[i].length < larga) return 'riga ' + i + ' corta (' + r[i].length + ' su ' + larga + ')';
      r[i] = r[i].padEnd(larga, '.');
      if (/[^.#%o^v<>*a]/.test(r[i])) return 'carattere sconosciuto alla riga ' + i;
    }
    for (const c of [0, 1, larga - 2, larga - 1]) {
      for (let i = 13; i < 17; i++) if (r[i][c] !== '.') return 'bordo occupato (colonna ' + c + ', riga ' + i + ')';
      for (let i = 17; i < 22; i++) if (r[i][c] !== '#') return 'manca il pavimento (colonna ' + c + ', riga ' + i + ')';
    }
    def.righe = r;
    return null;
  }

  for (const s of STANZE) {
    const e = prepara(s);
    if (e) throw new Error('Stanza ' + s.id + ': ' + e);
  }

  const API = { STANZE };
  if (typeof module !== 'undefined' && module.exports) module.exports = API;
  else radice.SpeedtinoStanze = API;
